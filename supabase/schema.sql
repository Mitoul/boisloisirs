-- Bois Loisirs: base Supabase pour le portail d'administration et les demandes.
-- 1) Créez un projet Supabase.
-- 2) Exécutez ce fichier dans SQL Editor.
-- 3) Créez ensuite un utilisateur dans Authentication > Users.
-- 4) Ajoutez son UUID dans public.admin_users.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.site_settings (
  id integer primary key default 1 check (id = 1),
  wood_price_small numeric(10,2) not null default 115,
  wood_price_large numeric(10,2) not null default 110,
  updated_at timestamptz not null default now()
);

insert into public.site_settings (id, wood_price_small, wood_price_large)
values (1, 115, 110)
on conflict (id) do nothing;

create table if not exists public.site_media (
  id bigint generated by default as identity primary key,
  product text not null check (product in ('wood','pellets')),
  slot text not null unique,
  url text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  request_type text not null check (request_type in ('commande','devis')),
  last_name text not null,
  first_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  postal_code text not null,
  city text not null,
  product text not null check (product in ('bois','pellets','service')),
  service text,
  quantity text,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.contact_requests add column if not exists service text;

alter table public.admin_users enable row level security;
alter table public.site_settings enable row level security;
alter table public.site_media enable row level security;
alter table public.contact_requests enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

create policy "public can read site settings"
on public.site_settings for select
using (true);

create policy "admins can update site settings"
on public.site_settings for update
using (public.is_admin())
with check (public.is_admin());

create policy "public can read media"
on public.site_media for select
using (true);

create policy "admins can insert media"
on public.site_media for insert
with check (public.is_admin());

create policy "admins can update media"
on public.site_media for update
using (public.is_admin())
with check (public.is_admin());

create policy "public can submit contact requests"
on public.contact_requests for insert
with check (true);

create policy "admins can read contact requests"
on public.contact_requests for select
using (public.is_admin());

